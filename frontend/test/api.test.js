import test from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import {
  listBicycles,
  getBicycle,
  createBicycle,
  updateBicycle,
  deleteBicycle,
  ApiError,
} from '../src/api.js';
import { createApp } from '../../backend/src/app.js';

test('Frontend API client - client-side validation', async () => {
  await assert.rejects(
    () => createBicycle({ name: '', brand: 'Giant', type: 'Road', price: 100 }),
    (err) => err instanceof ApiError && err.code === 'VALIDATION_ERROR' && err.message.includes('name')
  );

  await assert.rejects(
    () => createBicycle({ name: 'Speedster', brand: '', type: 'Road', price: 100 }),
    (err) => err instanceof ApiError && err.code === 'VALIDATION_ERROR' && err.message.includes('brand')
  );

  await assert.rejects(
    () => createBicycle({ name: 'Speedster', brand: 'Giant', type: '   ', price: 100 }),
    (err) => err instanceof ApiError && err.code === 'VALIDATION_ERROR' && err.message.includes('type')
  );

  await assert.rejects(
    () => createBicycle({ name: 'Speedster', brand: 'Giant', type: 'Road', price: -5 }),
    (err) => err instanceof ApiError && err.code === 'VALIDATION_ERROR' && err.message.includes('price')
  );

  await assert.rejects(
    () => updateBicycle('', { name: 'Speedster', brand: 'Giant', type: 'Road', price: 100 }),
    (err) => err instanceof ApiError && err.code === 'VALIDATION_ERROR' && err.message.includes('id')
  );
});

test('Frontend API client - contract error envelopes unwrapping', async () => {
  const server = http.createServer((req, res) => {
    if (req.url === '/api/bicycles/missing') {
      res.writeHead(404, { 'Content-Type': 'application/json' });
      res.end(JSON.stringify({
        success: false,
        data: null,
        error: { code: 'NOT_FOUND', message: 'Bicycle not found' },
      }));
      return;
    }

    if (req.url === '/api/bicycles/server-error') {
      res.writeHead(500, { 'Content-Type': 'application/json' });
      res.end(JSON.stringify({
        success: false,
        data: null,
        error: { code: 'INTERNAL_ERROR', message: 'Internal error' },
      }));
      return;
    }
  });

  await new Promise((resolve) => server.listen(0, resolve));
  const port = server.address().port;
  const baseUrl = `http://localhost:${port}/api/bicycles`;

  try {
    await assert.rejects(
      () => getBicycle('missing', { baseUrl }),
      (err) => err instanceof ApiError && err.code === 'NOT_FOUND' && err.status === 404
    );

    await assert.rejects(
      () => getBicycle('server-error', { baseUrl }),
      (err) => err instanceof ApiError && err.code === 'INTERNAL_ERROR' && err.status === 500
    );
  } finally {
    server.close();
  }
});

test('Frontend API client - end-to-end integration with backend Express app', async () => {
  const app = createApp();
  const server = http.createServer(app);

  await new Promise((resolve) => server.listen(0, resolve));
  const port = server.address().port;
  const baseUrl = `http://localhost:${port}/api/bicycles`;

  try {
    // 1. Initial list should be empty
    const initialList = await listBicycles({ page: 1, pageSize: 10, baseUrl });
    assert.deepEqual(initialList.items, []);
    assert.equal(initialList.meta.total, 0);

    // 2. Create bicycle
    const created = await createBicycle(
      {
        name: 'Escape 3',
        brand: 'Giant',
        type: 'Hybrid',
        price: 550,
      },
      { baseUrl }
    );

    assert.ok(created.id, 'id should be generated by server');
    assert.equal(created.name, 'Escape 3');
    assert.equal(created.brand, 'Giant');
    assert.equal(created.type, 'Hybrid');
    assert.equal(created.price, 550);
    assert.ok(created.createdAt, 'createdAt should be generated by server');

    // 3. Get single bicycle
    const fetched = await getBicycle(created.id, { baseUrl });
    assert.deepEqual(fetched, created);

    // 4. Update bicycle
    const updated = await updateBicycle(
      created.id,
      {
        name: 'Escape 3 Disc',
        brand: 'Giant',
        type: 'Hybrid',
        price: 620,
      },
      { baseUrl }
    );
    assert.equal(updated.id, created.id);
    assert.equal(updated.name, 'Escape 3 Disc');
    assert.equal(updated.price, 620);

    // 5. List bicycles after create
    const updatedList = await listBicycles({ page: 1, pageSize: 10, baseUrl });
    assert.equal(updatedList.items.length, 1);
    assert.equal(updatedList.meta.total, 1);
    assert.equal(updatedList.items[0].name, 'Escape 3 Disc');

    // 6. Delete bicycle
    const deletedResult = await deleteBicycle(created.id, { baseUrl });
    assert.equal(deletedResult, null);

    // 7. Verify deletion: get, update, delete non-existent should fail with 404 NOT_FOUND
    await assert.rejects(
      () => getBicycle(created.id, { baseUrl }),
      (err) => err instanceof ApiError && err.code === 'NOT_FOUND' && err.status === 404
    );

    await assert.rejects(
      () => updateBicycle(created.id, { name: 'X', brand: 'Y', type: 'Z', price: 10 }, { baseUrl }),
      (err) => err instanceof ApiError && err.code === 'NOT_FOUND' && err.status === 404
    );

    await assert.rejects(
      () => deleteBicycle(created.id, { baseUrl }),
      (err) => err instanceof ApiError && err.code === 'NOT_FOUND' && err.status === 404
    );

    const finalList = await listBicycles({ page: 1, pageSize: 10, baseUrl });
    assert.equal(finalList.items.length, 0);
    assert.equal(finalList.meta.total, 0);
  } finally {
    server.close();
  }
});

test('Frontend API client - pagination and multi-item integration', async () => {
  const app = createApp();
  const server = http.createServer(app);

  await new Promise((resolve) => server.listen(0, resolve));
  const port = server.address().port;
  const baseUrl = `http://localhost:${port}/api/bicycles`;

  try {
    for (let i = 1; i <= 5; i++) {
      await createBicycle(
        {
          name: `Bike ${i}`,
          brand: 'BrandX',
          type: 'Road',
          price: 100 * i,
        },
        { baseUrl }
      );
    }

    const page1 = await listBicycles({ page: 1, pageSize: 2, baseUrl });
    assert.equal(page1.items.length, 2);
    assert.equal(page1.meta.page, 1);
    assert.equal(page1.meta.pageSize, 2);
    assert.equal(page1.meta.total, 5);
    assert.equal(page1.items[0].name, 'Bike 1');
    assert.equal(page1.items[1].name, 'Bike 2');

    const page2 = await listBicycles({ page: 2, pageSize: 2, baseUrl });
    assert.equal(page2.items.length, 2);
    assert.equal(page2.meta.page, 2);
    assert.equal(page2.items[0].name, 'Bike 3');
    assert.equal(page2.items[1].name, 'Bike 4');

    const page3 = await listBicycles({ page: 3, pageSize: 2, baseUrl });
    assert.equal(page3.items.length, 1);
    assert.equal(page3.items[0].name, 'Bike 5');
  } finally {
    server.close();
  }
});
